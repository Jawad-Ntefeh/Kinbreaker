import { createHash } from 'node:crypto';
import { cpSync, existsSync, readFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { defineConfig, type Plugin } from 'vitest/config';

/**
 * `virtual:art-manifest`: the list of files under public/art/, so the game only requests images
 * that exist (a missing image would be a 404 in the console). Placeholders are used for the rest.
 */
function artManifest(): Plugin {
  const id = 'virtual:art-manifest';
  const resolved = '\0' + id;
  const root = join(process.cwd(), 'public');
  const list = (dir: string): string[] =>
    existsSync(dir)
      ? readdirSync(dir).flatMap((n) => {
          const p = join(dir, n);
          return statSync(p).isDirectory() ? list(p) : [relative(root, p).split('\\').join('/')];
        })
      : [];
  return {
    name: 'art-manifest',
    resolveId: (source) => (source === id ? resolved : null),
    load: (source) => {
      if (source !== resolved) return null;
      const files = list(join(root, 'art'));
      // Content fingerprints: art URLs carry ?v=<hash>, so a regenerated sheet is never served
      // from a stale browser or CDN cache under the same name.
      const versions = Object.fromEntries(files.map((f) => [f, createHash('sha256').update(readFileSync(join(root, f))).digest('hex').slice(0, 10)]));
      return `export default ${JSON.stringify(files)};\nexport const versions = ${JSON.stringify(versions)};\nexport const artUrl = (f) => versions[f] ? f + '?v=' + versions[f] : f;`;
    },
    configureServer(server) {
      server.watcher.add(join(root, 'art'));
      server.watcher.on('all', (_e, file) => {
        if (file.includes(join('public', 'art'))) {
          const mod = server.moduleGraph.getModuleById(resolved);
          if (mod) server.moduleGraph.invalidateModule(mod);
        }
      });
    },
  };
}

/** Publish docs/art_review/ (generated by `npm run art`) at /art_review/ on the site. */
function artReview(): Plugin {
  return {
    name: 'art-review',
    apply: 'build',
    closeBundle() {
      const src = join(process.cwd(), 'docs/art_review');
      if (existsSync(src)) cpSync(src, join(process.cwd(), 'dist/art_review'), { recursive: true });
    },
  };
}

export default defineConfig({
  // Relative base so the build works from any sub-path (GitHub Pages, desktop wrapper).
  base: './',
  plugins: [artManifest(), artReview()],
  build: {
    outDir: 'dist',
    target: 'es2022',
  },
  test: {
    include: ['tests/**/*.test.ts'],
    environment: 'node',
  },
});
